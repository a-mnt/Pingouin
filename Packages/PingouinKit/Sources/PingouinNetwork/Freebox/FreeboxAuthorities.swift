    /// Certificats prêts à servir d'ancres de confiance.
    static func certificates() -> [SecCertificate] {
        [eccRoot, rsaRoot].compactMap { certificate(fromPEM: $0) }
    }

    /// Lit un certificat au format PEM. `nil` si le texte n'en est pas un.
    static func certificate(fromPEM pem: String) -> SecCertificate? {
        let base64 = pem
            .split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.hasPrefix("-----") }
            .joined()
        guard let data = Data(base64Encoded: base64) else { return nil }
        return SecCertificateCreateWithData(nil, data as CFData)
    }
